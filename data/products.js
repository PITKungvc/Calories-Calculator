// ฟังก์ชันค้นหาและจับคู่สินค้าทางการแบบอัจฉริยะ (Exact & Fuzzy Keyword Match)
export function matchOfficialProduct(detectedName, customCatalog = []) {
  if (!detectedName) return null;
  const lower = detectedName.toLowerCase();
  
  // รวมแคตตาล็อกตั้งต้นกับแคตตาล็อกที่ดึงมาจาก Database กลาง (ถ้ามี)
  const fullCatalog = [...customCatalog, ...OFFICIAL_PRODUCTS];
  
  // 1. ตรวจสอบแบบคีย์เวิร์ดตรงทุกคำก่อน (Highest Priority)
  for (const item of fullCatalog) {
    if (item.keywords && item.keywords.length > 0) {
      const isMatch = item.keywords.every(kw => lower.includes(kw.toLowerCase()));
      if (isMatch) return item;
    }
  }

  // 2. ตรวจสอบชื่อแบรนด์หรือชื่อสินค้าตรงบางส่วน
  for (const item of fullCatalog) {
    if (lower.includes(item.name.toLowerCase())) {
      return item;
    }
  }

  return null;
}
